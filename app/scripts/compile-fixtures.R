.libPaths(c(normalizePath("../.Rlib"),.libPaths()))
suppressPackageStartupMessages(library(lavaan))
suppressPackageStartupMessages(library(jsonlite))
source("src/r/compile.R")
fixtures <- fromJSON("../fixtures/models.json",simplifyVector=FALSE)
models <- lapply(fixtures,function(f){
  opts <- toJSON(list(preset=f$preset,groups=f$groups,fixedX=FALSE,meanstructure=f$groups>1),auto_unbox=TRUE)
  result <- sem_compile(f$syntax,opts)
  if (!result$ok) stop(result$message)
  list(id=f$id,title=f$title,syntax=f$syntax,model=result)
})
dir.create("tests/fixtures",recursive=TRUE,showWarnings=FALSE)
write_json(models,"tests/fixtures/compiled.json",auto_unbox=TRUE,pretty=TRUE,dataframe="rows",na="null",null="null",digits=16)
cat("Compiled seven fixtures with the application R adapter.\n")
extra <- fromJSON("tests/fixtures/extra-models.json",simplifyVector=FALSE)
compiled_extra <- lapply(extra,function(f){
  result <- sem_compile(f$syntax,toJSON(list(preset="sem",groups=f$groups,fixedX=FALSE,meanstructure=f$groups>1),auto_unbox=TRUE))
  if(!result$ok)stop(paste(f$id,result$message))
  list(id=f$id,model=result)
})
write_json(compiled_extra,"tests/fixtures/extra-compiled.json",auto_unbox=TRUE,pretty=TRUE,dataframe="rows",na="null",null="null",digits=16)
